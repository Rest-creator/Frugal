#!/usr/bin/env python3
"""IGM (Improvement Generation Mechanism) — V1 minimal implementation.

Per Docs/IGM-IEM-SPEC.md: IGM reads a Finding, reads the current tool
(read-only), and writes a Candidate into candidates/ only. It never writes
to live tool config, never touches benchmarks/protected/, and never
approves or deploys anything.

V1 scope note (honest, not Potemkin): this generator is deterministic,
scoped to Finding #001's exact failure mode, not yet backed by an LLM call.
It is structured so a later version can swap the body of
`generate_fix_for_finding_001()` for an Anthropic API call that reads the
same inputs (finding text + current tool source) and produces the same
Candidate schema — the interface contract (read findings/current tool,
write only to candidates/) does not change when that swap happens. That
swap is tracked as a follow-up in README.md, not silently assumed done.

Usage: generate_candidate.py <finding_id>
"""
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANDIDATES_DIR = ROOT / "candidates"
CURRENT_TOOL = ROOT / "lab" / "tools" / "baseline-ssh-detector" / "detect.py"

IMPROVED_DETECTOR_SOURCE = '''#!/usr/bin/env python3
"""Improved SSH brute-force detector — candidate CAND-001.

Generated by IGM against FINDING-001-distributed-ssh-bruteforce.md.

Adds account-level correlation ACROSS source IPs, on top of the existing
per-IP check, so a distributed attack where each IP stays under the
per-IP threshold is still caught once the account-wide total crosses the
threshold and more than one source IP is involved.

Usage: detect.py <path-to-auth.log> [threshold]
"""
import re
import sys
from collections import defaultdict

FAILED_RE = re.compile(
    r"Failed password for (?:invalid user )?(?P<user>\\S+) from (?P<ip>\\d+\\.\\d+\\.\\d+\\.\\d+)"
)


def analyze(log_path: str, threshold: int):
    per_ip = defaultdict(lambda: defaultdict(int))   # ip -> user -> count
    per_user_ips = defaultdict(set)                  # user -> set of ips
    per_user_total = defaultdict(int)                # user -> total failed attempts

    with open(log_path) as f:
        for line in f:
            m = FAILED_RE.search(line)
            if m:
                user = m.group("user")
                ip = m.group("ip")
                per_ip[ip][user] += 1
                per_user_ips[user].add(ip)
                per_user_total[user] += 1

    alerts = []

    # Original per-IP check (kept — this must not regress).
    for ip, users in per_ip.items():
        for user, count in users.items():
            if count >= threshold:
                alerts.append({
                    "type": "per_ip_threshold",
                    "ip": ip,
                    "user": user,
                    "failed_attempts": count,
                })

    # New: account-level correlation across distinct source IPs.
    for user, total in per_user_total.items():
        distinct_ips = len(per_user_ips[user])
        if total >= threshold and distinct_ips >= 2:
            alerts.append({
                "type": "distributed_account_threshold",
                "user": user,
                "distinct_source_ips": distinct_ips,
                "total_failed_attempts": total,
            })

    return {
        "per_ip_failed_counts": per_ip,
        "per_user_totals": per_user_total,
        "per_user_distinct_ips": {u: len(ips) for u, ips in per_user_ips.items()},
        "alerts": alerts,
    }


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("usage: detect.py <path-to-auth.log> [threshold]")
        sys.exit(1)

    log_path = sys.argv[1]
    threshold = int(sys.argv[2]) if len(sys.argv) > 2 else 5

    result = analyze(log_path, threshold)

    print(f"Threshold: {threshold} (per-IP, and account-wide across >=2 distinct IPs)\\n")
    print("Per-IP failed attempt counts:")
    for ip, users in result["per_ip_failed_counts"].items():
        for user, count in users.items():
            print(f"  {ip} -> {user}: {count}")

    print("\\nPer-account totals across all source IPs:")
    for user, total in result["per_user_totals"].items():
        print(f"  {user}: {total} attempts from {result['per_user_distinct_ips'][user]} distinct IP(s)")

    print("\\nAlerts:")
    if result["alerts"]:
        for a in result["alerts"]:
            if a["type"] == "per_ip_threshold":
                print(f"  ALERT: {a['ip']} exceeded per-IP threshold against {a['user']} ({a['failed_attempts']} attempts)")
            else:
                print(f"  ALERT: distributed brute-force against {a['user']} -- {a['total_failed_attempts']} attempts across {a['distinct_source_ips']} distinct source IPs")
    else:
        print("  (none)")
'''


def generate_fix_for_finding_001() -> str:
    return IMPROVED_DETECTOR_SOURCE


def main():
    if len(sys.argv) < 2:
        print("usage: generate_candidate.py <finding_id>")
        sys.exit(1)

    finding_id = sys.argv[1]
    finding_path = CANDIDATES_DIR / f"{finding_id}.md"
    if not finding_path.exists():
        print(f"finding not found: {finding_path}")
        sys.exit(1)

    if finding_id != "FINDING-001-distributed-ssh-bruteforce":
        print(f"IGM V1 only knows how to generate a fix for FINDING-001; got {finding_id}")
        sys.exit(1)

    candidate_id = "CAND-001-distributed-ssh-bruteforce"
    out_dir = CANDIDATES_DIR / candidate_id
    out_dir.mkdir(parents=True, exist_ok=True)

    detector_source = generate_fix_for_finding_001()
    (out_dir / "detect.py").write_text(detector_source)

    metadata = {
        "id": candidate_id,
        "finding_id": finding_id,
        "target_tool": "lab/tools/baseline-ssh-detector/detect.py",
        "diff_or_new_artifact": f"candidates/{candidate_id}/detect.py",
        "rationale": (
            "The current tool only aggregates failed logins per (ip, user). "
            "Finding #001's evidence shows 3 source IPs each making 3 failed "
            "attempts against the same account (9 total) producing no alert. "
            "This candidate adds a second, independent check: total failed "
            "attempts for an account across all source IPs, gated on the "
            "attempt coming from 2+ distinct IPs so a single legitimate user "
            "mistyping their own password repeatedly from one machine is not "
            "flagged. The original per-IP check is kept unchanged so existing "
            "single-source brute-force detection does not regress."
        ),
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "generated_by": "igm/generate_candidate.py (deterministic V1, not yet LLM-backed)",
    }
    (out_dir / "candidate.json").write_text(json.dumps(metadata, indent=2) + "\n")

    print(f"Wrote candidate: {out_dir}")
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
