#!/usr/bin/env python3
"""Improved SSH brute-force detector — candidate CAND-001.

Generated by IGM against FINDING-001-distributed-ssh-bruteforce.md.

Adds account-level correlation ACROSS source IPs, on top of the existing
per-IP check, so a distributed attack where each IP stays under the
per-IP threshold is still caught once the account-wide total crosses the
threshold and more than one source IP is involved.

Usage: detect.py <path-to-auth.log> [threshold]
"""
import re
import sys
from collections import defaultdict

FAILED_RE = re.compile(
    r"Failed password for (?:invalid user )?(?P<user>\S+) from (?P<ip>\d+\.\d+\.\d+\.\d+)"
)


def analyze(log_path: str, threshold: int):
    per_ip = defaultdict(lambda: defaultdict(int))   # ip -> user -> count
    per_user_ips = defaultdict(set)                  # user -> set of ips
    per_user_total = defaultdict(int)                # user -> total failed attempts

    with open(log_path) as f:
        for line in f:
            m = FAILED_RE.search(line)
            if m:
                user = m.group("user")
                ip = m.group("ip")
                per_ip[ip][user] += 1
                per_user_ips[user].add(ip)
                per_user_total[user] += 1

    alerts = []

    # Original per-IP check (kept — this must not regress).
    for ip, users in per_ip.items():
        for user, count in users.items():
            if count >= threshold:
                alerts.append({
                    "type": "per_ip_threshold",
                    "ip": ip,
                    "user": user,
                    "failed_attempts": count,
                })

    # New: account-level correlation across distinct source IPs.
    for user, total in per_user_total.items():
        distinct_ips = len(per_user_ips[user])
        if total >= threshold and distinct_ips >= 2:
            alerts.append({
                "type": "distributed_account_threshold",
                "user": user,
                "distinct_source_ips": distinct_ips,
                "total_failed_attempts": total,
            })

    return {
        "per_ip_failed_counts": per_ip,
        "per_user_totals": per_user_total,
        "per_user_distinct_ips": {u: len(ips) for u, ips in per_user_ips.items()},
        "alerts": alerts,
    }


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("usage: detect.py <path-to-auth.log> [threshold]")
        sys.exit(1)

    log_path = sys.argv[1]
    threshold = int(sys.argv[2]) if len(sys.argv) > 2 else 5

    result = analyze(log_path, threshold)

    print(f"Threshold: {threshold} (per-IP, and account-wide across >=2 distinct IPs)\n")
    print("Per-IP failed attempt counts:")
    for ip, users in result["per_ip_failed_counts"].items():
        for user, count in users.items():
            print(f"  {ip} -> {user}: {count}")

    print("\nPer-account totals across all source IPs:")
    for user, total in result["per_user_totals"].items():
        print(f"  {user}: {total} attempts from {result['per_user_distinct_ips'][user]} distinct IP(s)")

    print("\nAlerts:")
    if result["alerts"]:
        for a in result["alerts"]:
            if a["type"] == "per_ip_threshold":
                print(f"  ALERT: {a['ip']} exceeded per-IP threshold against {a['user']} ({a['failed_attempts']} attempts)")
            else:
                print(f"  ALERT: distributed brute-force against {a['user']} -- {a['total_failed_attempts']} attempts across {a['distinct_source_ips']} distinct source IPs")
    else:
        print("  (none)")
